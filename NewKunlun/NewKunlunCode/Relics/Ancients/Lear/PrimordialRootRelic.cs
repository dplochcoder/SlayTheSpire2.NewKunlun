using NewKunlun.NewKunlunCode.Extensions;
using NewKunlun.NewKunlunCode.Localization;

namespace NewKunlun.NewKunlunCode.Relics.Ancients.Lear;

[Pool(typeof(SharedRelicPool))]
[RelicLocalization(
    title: "Primordial Root",
    description: "At the start of your turn, gain {Energy:energyIcons()} and add one [gold]Fade[/gold] to your discard pile.",
    flavor: ""
)]
public partial class PrimordialRootRelic : NewKunlunRelic
{
    public override RelicRarity Rarity => RelicRarity.Ancient;

    protected override IEnumerable<DynamicVar> CanonicalVars => [new EnergyVar(1)];

    protected override IEnumerable<IHoverTip> ExtraHoverTips =>
        [HoverTipFactory.FromCard<FadeCard>()];

    public override decimal ModifyMaxEnergy(Player player, decimal amount) =>
        player == Owner ? amount + Energy.IntValue : amount;

    public override async Task AfterSideTurnStart(
        CombatSide side,
        IReadOnlyList<Creature> participants,
        ICombatState combatState
    )
    {
        if (side != Owner.Creature.Side)
            return;

        await Owner.AddGeneratedCardToPile<FadeCard>(PileType.Discard);
    }
}
